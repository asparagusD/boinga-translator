"""Build a per-chunk Colab notebook from a spec (notebooks/specs/*.py) into notebooks/runs/."""

# Usage: python tools/build_notebook.py notebooks/specs/<spec>.py [--check]
#        python tools/build_notebook.py --all [--check]
# Layout: title, bootstrap cells BOOT.1-4 (BRANCH baked in), run header HDR, spec cells,
# then "Your observations" with the spec's forms. Output is deterministic: no outputs,
# no execution counts, LF line endings. all_cells() is what the reader checks against.

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import re
import sys
from pathlib import Path

import nbkit

ROOT = Path(__file__).resolve().parent.parent
SPECS = "notebooks/specs"
RUNS = "notebooks/runs"
BOOTSTRAP = "notebooks/colab_bootstrap.py"
_BOOT_CELL = re.compile(r"^# %% Cell (\d+)/\d+ - (.+)$", re.MULTILINE)
_BRANCH_LINE = re.compile(r'^BRANCH = "main"(.*)$', re.MULTILINE)
_CHUNK = re.compile(r"^[A-Za-z0-9]+$")


def load_spec(spec: Path) -> nbkit.Notebook:
    """Import a spec file and return its NOTEBOOK."""
    mod_spec = importlib.util.spec_from_file_location(f"boinga_spec_{spec.stem}", spec)
    if mod_spec is None or mod_spec.loader is None:
        raise ValueError(f"{spec}: cannot import this spec file")
    module = importlib.util.module_from_spec(mod_spec)
    mod_spec.loader.exec_module(module)
    notebook = getattr(module, "NOTEBOOK", None)
    if not isinstance(notebook, nbkit.Notebook):
        raise TypeError(f"{spec}: must define NOTEBOOK = nbkit.Notebook(...)")
    if not _CHUNK.match(notebook.chunk):
        raise ValueError(f"{spec}: chunk must be letters and digits, got {notebook.chunk!r}")
    return notebook


def filename(nb: nbkit.Notebook) -> str:
    return f"{nb.chunk}_{nb.slug}_run{nb.run}.ipynb"


def bootstrap_cells(branch: str) -> list[nbkit.Cell]:
    """The 4 bootstrap cells as BOOT.1-4, with BRANCH set to the spec's branch."""
    text = (ROOT / BOOTSTRAP).read_text(encoding="utf-8")
    text, count = _BRANCH_LINE.subn(f"BRANCH = {json.dumps(branch)}  # set by build_notebook",
                                    text)
    if count != 1:
        raise ValueError(f"{BOOTSTRAP}: expected one 'BRANCH = \"main\"' line, found {count}")
    heads = list(_BOOT_CELL.finditer(text))
    cells = []
    for head, nxt in zip(heads, [*heads[1:], None], strict=True):
        body = text[head.end():nxt.start() if nxt else len(text)].strip("\n")
        cid, title = f"BOOT.{head.group(1)}", head.group(2)
        cells.append(nbkit.Cell("code", f"# [boinga {cid}] {title}\n{body}", cid, title,
                                (r"^PASS:",), nbkit.ALWAYS_FORBID))
    if [c.id for c in cells] != ["BOOT.1", "BOOT.2", "BOOT.3", "BOOT.4"]:
        raise ValueError(f"{BOOTSTRAP}: expected cells 1/4..4/4, got {[c.id for c in cells]}")
    return cells


def _title_cell(nb: nbkit.Notebook, spec_rel: str) -> nbkit.Cell:
    steps = [
        'Open this notebook in Colab (File > Open notebook > GitHub, tick "Include private'
        ' repos").' + (" Runtime > Change runtime type > T4 GPU." if nb.gpu else ""),
        ("First time on a VM: the Colab secret GH_TOKEN must exist with notebook access "
         f"(see `{BOOTSTRAP}`)."),
        "Runtime > Run all. A failing cell stops the run on purpose: don't skip it.",
        *(['Fill in the forms under "Your observations" and run each form cell again.']
          if nb.forms else []),
        (f"File > Download > Download .ipynb, save it as `colab_runs/{filename(nb)}` in the "
         "repo, and tell Claude Code."),
    ]
    return nbkit.md("\n".join([
        f"# {nb.chunk} run {nb.run} — {nb.title}", "",
        (f"Branch `{nb.branch}` · spec `{spec_rel}` · generated by `tools/build_notebook.py`"
         " (do not edit)."), "", "## What to do",
        *(f"{i}. {s}" for i, s in enumerate(steps, 1))]))


def all_cells(nb: nbkit.Notebook, spec_rel: str) -> list[nbkit.Cell]:
    """Every cell of the built notebook, in order."""
    header = nbkit.Cell("code", "# [boinga HDR] Run header\nfrom boinga_translator.colab_runtime"
                        f" import run_header; run_header({nb.chunk!r}, {nb.run})", "HDR",
                        "Run header", (), nbkit.ALWAYS_FORBID)
    cells = [_title_cell(nb, spec_rel), *bootstrap_cells(nb.branch), header,
             *(c for c in nb.cells if c.kind != "form")]
    if nb.forms:
        cells += [nbkit.md('## Your observations\n\nFill these in after "Run all", then run'
                           " each form cell again."), *nb.forms]
    return cells


def _lines(text: str) -> list[str]:
    lines = text.splitlines(keepends=True)
    if lines:
        lines[-1] = lines[-1].rstrip("\n")
    return lines


def build(spec: Path) -> tuple[str, str]:
    """Return (repo-relative output path, .ipynb JSON text) for one spec file."""
    nb = load_spec(spec)
    spec_rel = spec.resolve().relative_to(ROOT.resolve()).as_posix()
    text = spec.read_text(encoding="utf-8").replace("\r\n", "\n")
    cells, seen = [], set()
    for i, cell in enumerate(all_cells(nb, spec_rel)):
        nb_id = re.sub(r"[^A-Za-z0-9_-]", "-", cell.id) if cell.id else f"md-{i}"
        if nb_id in seen:
            raise ValueError(f"{spec_rel}: cell id {cell.id!r} clashes with another cell")
        seen.add(nb_id)
        entry = {"cell_type": cell.kind if cell.kind == "markdown" else "code", "id": nb_id,
                 "metadata": cell.metadata, "source": _lines(cell.source)}
        if entry["cell_type"] == "code":
            entry.update(execution_count=None, outputs=[])
        cells.append(entry)
    metadata: dict[str, object] = {
        "boinga": {"chunk": nb.chunk, "run": nb.run, "slug": nb.slug, "branch": nb.branch,
                   "spec": spec_rel,
                   "spec_sha256": hashlib.sha256(text.encode("utf-8")).hexdigest()},
        "colab": {"provenance": [], **({"gpuType": "T4"} if nb.gpu else {})},
        "kernelspec": {"display_name": "Python 3", "name": "python3"},
        "language_info": {"name": "python"},
        **({"accelerator": "GPU"} if nb.gpu else {}),
    }
    doc = {"cells": cells, "metadata": metadata, "nbformat": 4, "nbformat_minor": 5}
    return f"{RUNS}/{filename(nb)}", json.dumps(doc, indent=1, ensure_ascii=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("specs", nargs="*", help="spec files, e.g. notebooks/specs/env_check.py")
    ap.add_argument("--all", action="store_true", help=f"build every spec in {SPECS}/")
    ap.add_argument("--check", action="store_true", help="exit 1 if a notebook is stale")
    args = ap.parse_args(argv)
    specs = [ROOT / s for s in args.specs]
    if args.all:
        specs += sorted(p for p in (ROOT / SPECS).glob("*.py") if not p.name.startswith("_"))
    if not specs and not args.all:
        ap.error("give spec files or --all")
    stale, built = [], set()
    for spec in specs:
        rel, text = build(spec)
        if rel in built:
            print(f"error: two specs build {rel}: chunk + slug + run must be unique",
                  file=sys.stderr)
            return 1
        built.add(rel)
        target = ROOT / rel
        if args.check:
            current = target.read_text(encoding="utf-8") if target.is_file() else None
            if current != text:
                stale.append(rel)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {rel}")
    if args.all and args.check:  # a run notebook no spec builds any more (e.g. run bumped)
        stale += sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / RUNS).glob("*.ipynb")
                        if p.relative_to(ROOT).as_posix() not in built)
    if stale:
        print(f"stale notebooks: {', '.join(stale)}. Run `python tools/build_notebook.py "
              "--all` (and delete run notebooks no spec builds).", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
